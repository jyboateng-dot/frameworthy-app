import { chromium } from 'playwright';
import { readFile } from 'node:fs/promises';
const browser = await chromium.launch({ headless: true });
try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    const picture = await readFile('scratch/ig_profile_logo.png');
    await page.route('**/fit-fixture.png', r => r.fulfill({ contentType: 'image/png', body: picture }));
    await page.route('**/getImageKitUploadAuth', r => r.fulfill({ json: { result: { signature: 'test', token: 'test', expire: 9999999999 } } }));
    await page.route('https://upload.imagekit.io/**', r => r.fulfill({ json: { url: 'http://localhost:5173/fit-fixture.png' } }));
    await page.addInitScript(() => { localStorage.setItem('fw_tester_access', 'granted'); localStorage.setItem('fw_tester_carousel_seen', 'true'); });
    await page.goto('http://localhost:5173/frame/customize');
    await page.getByRole('button', { name: /upload image/i }).click();
    await page.locator('input[type=file]').setInputFiles({ name: 'portrait.png', mimeType: 'image/png', buffer: picture });
    await page.getByRole('button', { name: 'Best Fit', exact: true }).waitFor();
    const positionSection = page.locator('section').filter({ has: page.getByRole('heading', { name: '4 Image Position' }) });
    await positionSection.screenshot({ path: 'scratch/frame-fit-position.png' });
    await page.getByRole('button', { name: 'Best Fit', exact: true }).click();
    await page.getByRole('dialog').waitFor();
    await page.screenshot({ path: 'scratch/frame-fit-desktop.png' });
    await page.getByRole('button', { name: 'Apply', exact: true }).first().click();
    await page.getByRole('button', { name: 'Undo fit change' }).click();
    await page.getByRole('button', { name: 'Best Fit', exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: /^Apply .+/ }).first().click();
    await page.getByRole('button', { name: 'Undo fit change' }).click();
    await page.getByRole('slider', { name: 'Zoom', exact: true }).fill('1.5');
    await page.getByRole('button', { name: 'Add to Cart', exact: true }).click();
    await page.getByRole('dialog', { name: 'Review your frame' }).waitFor();
    await page.screenshot({ path: 'scratch/frame-fit-review.png' });
    await page.getByRole('button', { name: 'Adjust Frame', exact: true }).click();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: 'Best Fit', exact: true }).click();
    await page.screenshot({ path: 'scratch/frame-fit-mobile.png' });
    await page.getByRole('button', { name: 'Close frame review' }).click();
    await page.getByRole('button', { name: 'Add to Cart', exact: true }).click();
    await page.getByRole('button', { name: 'Confirm Frame', exact: true }).click();
    await page.getByRole('dialog', { name: 'Review your frame' }).waitFor({ state: 'hidden' });
    const saved = await page.evaluate(() => Object.values(localStorage).some(value => value.includes('printIsCropped')));
    if (!saved) throw new Error('Production crop specification was not saved in cart');
    if (errors.length) throw new Error(errors.join('\n'));
    console.log('PASS: best fit, apply, undo, zoom, review, desktop and mobile; no page errors. Uploads mocked.');
} finally { await browser.close(); }
